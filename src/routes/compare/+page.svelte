	// Read `model=` and `benchmark=` from the URL. Accepts both the legacy
	// repeated form (`?model=a&model=b`, generated by external share links)
	// and the comma-separated form (`?model=a,b`) that we write going
	// forward — so existing pasted links keep working.
	//
	// The split must run on the RAW (still URL-encoded) value, not on
	// the auto-decoded `searchParams.get()` result. Benchmark / model
	// names can legitimately contain commas (`MTEB(Multilingual, v2)`)
	// which the writer correctly escapes to `%2C` before joining with
	// a literal `,` separator. Decoding first would erase that
	// distinction and split inside names. Decode each part *after* the
	// split — mirrors `decodeSet` in url-state.ts.
	function readMultiParam(url: URL, name: string): string[] {
		const repeated = url.searchParams.getAll(name);
		if (repeated.length > 1) return repeated;
		const encodedKey = encodeURIComponent(name);
		const rawSearch = url.search.startsWith('?') ? url.search.slice(1) : url.search;
		if (!rawSearch) return [];
		for (const pair of rawSearch.split('&')) {
			const eq = pair.indexOf('=');
			const k = eq < 0 ? pair : pair.slice(0, eq);
			// Compare keys after `+`→space conversion so form-encoded
			// keys still match plain ones.
			if (decodeURIComponent(k.replace(/\+/g, '%20')) !== name && k !== encodedKey) continue;
			const rawValue = eq < 0 ? '' : pair.slice(eq + 1);
			if (!rawValue) return [];
			return rawValue
				.split(',')
				.map((s) => decodeURIComponent(s.replace(/\+/g, '%20')))
				.map((s) => s.trim())
				.filter(Boolean);
		}
		return [];
	}

	const MAX_PICKED = 4;
	const MAX_BENCHMARKS = 6;
	const MAX_TASKS = 12;
	const RADAR_COLORS = ['#9333EA', '#00a6ed', '#ECA72C', '#3CBBB1'];

	let ALL_BENCHMARKS = $state<Benchmark[]>([]);
	// Local derived lookup, not held in $state — plain Map is correct.

	let benchIndex = $derived(new Map(ALL_BENCHMARKS.map((b) => [b.name, b])));
	// Plain Map + a version counter — cheaper than SvelteMap's per-key
	// proxy. Consumers bump `summaryCacheVersion` on insert to invalidate
	// the `benchSummaries` derived.
	// eslint-disable-next-line svelte/prefer-svelte-reactivity
	const summaryCache = new Map<string, BenchmarkSummary>();
	let summaryCacheVersion = $state(0);

	$effect(() => {
